#!/usr/bin/env python3
"""Check the control-framework mappings (fedora/mappings/*.yaml) and the table
generated from them (docs/MAPPING.md).

    python3 tests/check-mappings.py           # lint; exit 1 on a problem or a stale table
    python3 tests/check-mappings.py --write   # regenerate docs/MAPPING.md

The mappings are references, never framework text, and never feed the script: a
problem here fails CI, it changes nothing a run does. IDs are checked for the shape
each pinned edition uses (an ATT&CK for ICS ID such as M0918 is rejected, since the
mappings use ATT&CK Enterprise); whether an ID fits a section is a review question.
"""

from __future__ import annotations

import argparse
import datetime as dt
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
MAPPINGS = ROOT / "fedora" / "mappings"
SECTIONS = ROOT / "fedora" / "sections"
TABLE = ROOT / "docs" / "MAPPING.md"

CSF = "nist-csf-2.0"
SP = "nist-sp-800-53r5"
ATTACK = "mitre-attack-enterprise-v20.1"
KEYS = {"section", "reviewed", CSF, SP, ATTACK, "benchmarks"}
CSF_ID = re.compile(r"^(GV|ID|PR|DE|RS|RC)\.[A-Z]{2}-\d{2}$")
SP_ID = re.compile(r"^[A-Z]{2}-\d{1,2}(\(\d{1,2}\))?$")
MITIGATION_ID = re.compile(r"^M1\d{3}$")
TECHNIQUE_ID = re.compile(r"^T\d{4}(\.\d{3})?$")

EDITIONS = """\
| Framework | Edition pinned | Source |
|---|---|---|
| NIST Cybersecurity Framework | 2.0 (CSWP 29, February 2024) | [doi.org/10.6028/NIST.CSWP.29](https://doi.org/10.6028/NIST.CSWP.29) |
| NIST SP 800-53 | Revision 5, release 5.2.0 | [csrc.nist.gov](https://csrc.nist.gov/projects/cprt/catalog#/cprt/framework/version/SP_800_53_5_2_0/home) |
| MITRE ATT&CK | Enterprise v20.1 | [attack.mitre.org](https://attack.mitre.org/) |
"""


def problems_in(path: Path, data: object) -> list[str]:
    errs: list[str] = []
    if not isinstance(data, dict):
        return [f"{path.name}: not a mapping"]
    extra, missing = set(data) - KEYS, KEYS - set(data)
    if extra:
        errs.append(f"{path.name}: unknown keys {sorted(extra)} (editions are part of the key)")
    if missing:
        errs.append(f"{path.name}: missing keys {sorted(missing)}")
    sec = data.get("section")
    prefix = path.name.split("-", 1)[0]
    if not isinstance(sec, int) or f"{sec:02d}" != prefix:
        errs.append(f"{path.name}: section {sec!r} doesn't match the file name")
    elif not list(SECTIONS.glob(f"{prefix}-*.sh")):
        errs.append(f"{path.name}: no fedora/sections/{prefix}-*.sh")
    if not isinstance(data.get("reviewed"), dt.date):
        errs.append(f"{path.name}: reviewed must be a date (YYYY-MM-DD)")

    def ids(key: str, value: object, pattern: re.Pattern) -> None:
        if not isinstance(value, list) or not value:
            errs.append(f"{path.name}: {key} must be a non-empty list")
            return
        for v in value:
            if not isinstance(v, str) or not pattern.match(v):
                errs.append(f"{path.name}: {key}: {v!r} isn't a valid ID")
        if len(set(value)) != len(value):
            errs.append(f"{path.name}: {key} lists an ID twice")

    ids(CSF, data.get(CSF), CSF_ID)
    ids(SP, data.get(SP), SP_ID)
    att = data.get(ATTACK)
    if not isinstance(att, dict) or set(att) != {"techniques", "mitigations"}:
        errs.append(f"{path.name}: {ATTACK} needs exactly techniques and mitigations")
    else:
        ids(f"{ATTACK}.techniques", att["techniques"], TECHNIQUE_ID)
        ids(f"{ATTACK}.mitigations", att["mitigations"], MITIGATION_ID)
    bench = data.get("benchmarks")
    if not isinstance(bench, list):
        errs.append(f"{path.name}: benchmarks must be a list (empty is fine)")
    else:
        for b in bench:
            need = {"name", "edition", "items", "authoritative"}
            if not isinstance(b, dict) or set(b) != need:
                errs.append(f"{path.name}: a benchmark needs exactly {sorted(need)}")
            elif "CIS" in b["name"] and "Fedora" not in b["name"] and b["authoritative"] is not False:
                errs.append(f"{path.name}: {b['name']} is a proxy for Fedora: authoritative must be false")
    return errs


def section_title(n: int) -> str:
    for f in SECTIONS.glob(f"{n:02d}-*.sh"):
        m = re.search(r"SECTION\s+\d+\s+—\s+(.+)", f.read_text())
        if m:
            return m.group(1).strip()
    return f"Section {n}"


def table(entries: list[dict]) -> str:
    rows = [
        "# Control-framework mapping",
        "",
        "<!-- Generated by tests/check-mappings.py --write from fedora/mappings/*.yaml. Edit those. -->",
        "",
        "Each hardening section, mapped to the controls of three public frameworks: NIST CSF",
        "2.0 subcategories, NIST SP 800-53 controls and MITRE ATT&CK techniques and",
        "mitigations. The mappings are references for a reviewer, a security lead or an",
        "auditor. They are not a compliance claim: running these sections doesn't make a",
        "machine compliant with any of these frameworks. They never change what the script",
        "does.",
        "",
        "Only ATT&CK mitigations that ATT&CK itself links to the listed techniques are used,",
        "and only where the section does what the mitigation describes. No framework text",
        "is copied here: follow the IDs to the source.",
        "",
        "## Editions",
        "",
        EDITIONS,
        "## Sections",
        "",
        "| Section | CSF 2.0 | SP 800-53 Rev. 5 | ATT&CK techniques | ATT&CK mitigations | Benchmark proxy | Reviewed |",
        "|---|---|---|---|---|---|---|",
    ]
    for d in entries:
        n = d["section"]
        src = next(SECTIONS.glob(f"{n:02d}-*.sh")).relative_to(ROOT)
        bench = "; ".join(f"{b['name']} {b['edition']}: {', '.join(b['items'])}" for b in d["benchmarks"]) or "—"
        rows.append(
            f"| [{n}. {section_title(n)}](../{src}) | {', '.join(d[CSF])} | {', '.join(d[SP])} "
            f"| {', '.join(d[ATTACK]['techniques'])} | {', '.join(d[ATTACK]['mitigations'])} | {bench} | {d['reviewed']} |"
        )
    mapped = {d["section"] for d in entries}
    todo = sorted(int(f.name[:2]) for f in SECTIONS.glob("[0-9][0-9]-*.sh") if int(f.name[:2]) not in mapped)
    rows += [
        "",
        f"Not mapped yet: sections {', '.join(map(str, todo))}." if todo else "Every section is mapped.",
        "",
        "## Benchmarks",
        "",
        "There is no CIS benchmark for Fedora. Where a section lists one, it is the nearest",
        "relative (CIS Red Hat Enterprise Linux), marked as a proxy, with item numbers taken",
        "from the licensed benchmark; the benchmark's text is not reproduced.",
        "",
    ]
    return "\n".join(rows)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--write", action="store_true", help="regenerate docs/MAPPING.md")
    args = ap.parse_args()
    errs: list[str] = []
    entries = []
    for path in sorted(MAPPINGS.glob("*.yaml")):
        data = yaml.safe_load(path.read_text())
        found = problems_in(path, data)
        errs += found
        if not found:
            entries.append(data)
    if errs:
        print("\n".join(errs), file=sys.stderr)
        return 1
    text = table(entries)
    if args.write:
        TABLE.write_text(text)
        print(f"wrote {TABLE.relative_to(ROOT)} ({len(entries)} sections)")
        return 0
    if not TABLE.is_file() or TABLE.read_text() != text:
        print("docs/MAPPING.md is out of date: python3 tests/check-mappings.py --write", file=sys.stderr)
        return 1
    print(f"mappings OK ({len(entries)} sections)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
